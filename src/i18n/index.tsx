type Key = keyof typeof pt

type Value = {
  language: AppLanguage
  locale: string
  setLanguage: (value: AppLanguage) => void
  t: (
    key: Key,
    params?: Record<string, string | number>,
  ) => string
}

const Context = createContext<Value | null>(null)

function normalize(value?: string | null): AppLanguage | null {
  if (!value) return null
  if (['pt-BR', 'en', 'es', 'zh-CN', 'de'].includes(value)) {
    return value as AppLanguage
  }
  if (value.startsWith('pt')) return 'pt-BR'
  if (value.startsWith('en')) return 'en'
  if (value.startsWith('es')) return 'es'
  if (value.startsWith('zh')) return 'zh-CN'
  if (value.startsWith('de')) return 'de'
  return null
}

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [language, setLanguageState] = useState<AppLanguage>(
    () =>
      normalize(localStorage.getItem('rv_language')) ??
      normalize(navigator.language) ??
      'pt-BR',
  )

  const setLanguage = (value: AppLanguage) => {
    localStorage.setItem('rv_language', value)
    setLanguageState(value)
  }

  useEffect(() => {
    document.documentElement.lang = language
    document.documentElement.dataset.language = language
  }, [language])

  const value = useMemo<Value>(() => ({
    language,
    locale:
      languages.find((item) => item.value === language)?.locale ?? 'pt-BR',
    setLanguage,
    t: (key, params) => {
      let text = String(dictionaries[language][key] ?? pt[key])

      if (params) {
        Object.entries(params).forEach(([name, value]) => {
          text = text.replaceAll(`{${name}}`, String(value))
        })
      }

      return text
    },
  }), [language])

  return <Context.Provider value={value}>{children}</Context.Provider>
}

export function useI18n() {
  const value = useContext(Context)
  if (!value) throw new Error('LanguageProvider ausente')
  return value
}
